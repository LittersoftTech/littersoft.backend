{
    var handlerType = Assembly.Load(host).GetType($"{host}.GlobalExceptionHandler")!;
    var logger = Activator.CreateInstance(typeof(NullLogger<>).MakeGenericType(handlerType));
    var handler = (IExceptionHandler)Activator.CreateInstance(handlerType, logger)!;
    using var services = new ServiceCollection().AddLogging().BuildServiceProvider();
    var context = new DefaultHttpContext { RequestServices = services };
    context.Response.Body = new MemoryStream();
    var id = Guid.NewGuid(); var title = "Host's \"Morning\" 🐾";
    Check(await handler.TryHandleAsync(context, new HostEventOverlapException(id, title), default), $"{host} handles overlap exceptions");
    context.Response.Body.Position = 0;
    using var json = await JsonDocument.ParseAsync(context.Response.Body);
    var root = json.RootElement;
    Check(context.Response.StatusCode == 409 && root.GetProperty("code").GetString() == "HostEventOverlap"
        && root.GetProperty("conflictingEventId").GetGuid() == id && root.GetProperty("conflictingEventTitle").GetString() == title
        && !root.TryGetProperty("data", out _), $"{host} returns the requested direct 409 body with escaped title preserved");
}


async Task RunStore(IEventSqlStore store, Guid parent, Guid provider, string label, Func<Guid, Task> cancel)
{
    var day = new DateOnly(2030, 10, 12);
    foreach (var isParent in new[] { true, false })
    {
        var role = isParent ? "parent" : "provider";
        Task<EventSqlSnapshot> Create(DateOnly startDate, DateOnly endDate, TimeOnly start, TimeOnly end, string title = "Other") => isParent
            ? store.CreateByParentAsync(new(parent, "MeetupsAndSocials", true, title, "Description", null, [], "Online", startDate, endDate, start, end, false, null, null, null), default)
            : store.CreateAsync(new(provider, "MeetupsAndSocials", true, title, "Description", null, [], "Online", startDate, endDate, start, end, false, null, null, null), default);
        Task<EventSqlSnapshot> Update(EventSqlSnapshot e, DateOnly startDate, DateOnly endDate, TimeOnly start, TimeOnly end) => isParent
            ? store.UpdateByParentAsync(new(e.EventId, parent, e.EventCategory, e.IsChildFriendly, e.Title, e.Description, e.BannerImageUrl, e.Amenities, e.EventType, startDate, endDate, start, end, e.IsPaid, e.Price, e.CancellationPolicy, e.EventLink), default)
            : store.UpdateAsync(new(e.EventId, provider, e.EventCategory, e.IsChildFriendly, e.Title, e.Description, e.BannerImageUrl, e.Amenities, e.EventType, startDate, endDate, start, end, e.IsPaid, e.Price, e.CancellationPolicy, e.EventLink), default);
        async Task Conflict(Func<Task<EventSqlSnapshot>> action, EventSqlSnapshot expected, string name)
        {
            try { await action(); throw new Exception($"Expected conflict: {name}"); }
            catch (HostEventOverlapException ex)
            {
                Check(ex.ConflictingEventId == expected.EventId && ex.ConflictingEventTitle == expected.Title, $"{label} {role} {name}");
            }
        }
        var baseline = await Create(day, day, new(10, 0), new(12, 0), "Host's \"Morning\" 🐾");
        await Conflict(() => Create(day, day, new(11, 0), new(13, 0)), baseline, "rejects 11–13 against 10–12");
        await Conflict(() => Create(day, day, new(9, 0), new(10, 30)), baseline, "rejects 9–10:30 against 10–12");
        await Conflict(() => Create(day, day, new(10, 0), new(12, 0)), baseline, "rejects identical interval");
        await Conflict(() => Create(day, day, new(9, 0), new(13, 0)), baseline, "rejects containing interval");
        await Conflict(() => Create(day, day, new(10, 30), new(11, 0)), baseline, "rejects contained interval");
        var after = await Create(day, day, new(12, 0), new(13, 0));
        Check(after.EventId != baseline.EventId, $"{label} {role} allows back-to-back after");
        Check((await Create(day, day, new(9, 0), new(10, 0))).EventId != baseline.EventId, $"{label} {role} allows back-to-back before");
        var tomorrow = await Create(day.AddDays(1), day.AddDays(1), new(10, 0), new(12, 0));
        Check(tomorrow.EventId != baseline.EventId, $"{label} {role} allows same time on another date");
        Check((await Update(baseline, day, day, new(10, 15), new(11, 45))).EventId == baseline.EventId, $"{label} {role} edit excludes itself");
        await Conflict(() => Update(tomorrow, day, day, new(10, 30), new(11, 30)), baseline, "rejects date/time edit into another event");
        var unchanged = (await store.GetAsync(tomorrow.EventId, default))!;
        Check(unchanged.StartDate == day.AddDays(1) && unchanged.StartTime == new TimeOnly(10, 0), $"{label} {role} rejected edit leaves schedule unchanged");
        Check((await Update(tomorrow, day, day, new(13, 0), new(14, 0))).StartDate == day, $"{label} {role} allows non-overlapping schedule edit");
        var multiDay = await Create(day.AddDays(3), day.AddDays(5), new(22, 0), new(6, 0));
        await Conflict(() => Create(day.AddDays(4), day.AddDays(4), new(9, 0), new(10, 0)), multiDay, "checks complete multi-day intervals");
        Check((await Create(day.AddDays(5), day.AddDays(5), new(6, 0), new(7, 0))).EventId != multiDay.EventId, $"{label} {role} allows multi-day boundary adjacency");
        await cancel(baseline.EventId);
        Check((await Create(day, day, new(10, 0), new(12, 0))).EventId != baseline.EventId, $"{label} {role} ignores cancelled events");

        var raceDay = day.AddDays(20);
        var ready = new TaskCompletionSource(TaskCreationOptions.RunContinuationsAsynchronously);
        async Task<bool> Race(string title)
        {
            await ready.Task;
            try { await Create(raceDay, raceDay, new(10, 0), new(12, 0), title); return true; }
            catch (HostEventOverlapException) { return false; }
        }
        var first = Task.Run(() => Race("Device A")); var second = Task.Run(() => Race("Device B")); ready.SetResult();
        var outcomes = await Task.WhenAll(first, second);
        Check(outcomes.Count(x => x) == 1, $"{label} {role} simultaneous creates allow exactly one event");

        var moveDay = raceDay.AddDays(1);
        var morning = await Create(moveDay, moveDay, new(8, 0), new(9, 0));
        var evening = await Create(moveDay, moveDay, new(16, 0), new(17, 0));
        var editReady = new TaskCompletionSource(TaskCreationOptions.RunContinuationsAsynchronously);
        async Task<bool> Move(EventSqlSnapshot e)
        {
            await editReady.Task;
            try { await Update(e, moveDay, moveDay, new(13, 0), new(14, 0)); return true; }
            catch (HostEventOverlapException) { return false; }
        }
        var editA = Task.Run(() => Move(morning)); var editB = Task.Run(() => Move(evening)); editReady.SetResult();
        Check((await Task.WhenAll(editA, editB)).Count(x => x) == 1, $"{label} {role} simultaneous edits into one slot allow exactly one event");

        var spring = new DateOnly(2026, 3, 29);
        var springEvent = await Create(spring, spring, new(3, 0), new(4, 0));
        await Conflict(() => Create(spring, spring, new(2, 30), new(4, 30)), springEvent, "normalizes spring DST gap times consistently");
        Check((await Create(spring, spring, new(1, 30), new(2, 0))).EventId != springEvent.EventId,
            $"{label} {role} permits exact adjacency after DST normalization");
    }
    Check((await store.ListByPetParentAsync(parent, default)).Count > 0 && (await store.ListByProviderAsync(provider, default)).Count > 0,
        $"{label} different host accounts may run events at the same time");
}
